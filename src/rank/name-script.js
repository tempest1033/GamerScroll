'use strict';

// Script checks for per-edition game names (rank/stats.js displayName).
const HANGUL = /[\uAC00-\uD7A3]/;
const KANA = /[\u3040-\u30FF]/;
const CJK = /[\u3040-\u30FF\u3400-\u9FFF\uAC00-\uD7A3]/;
// Characters that exist only in Simplified Chinese (never a Traditional form), generated from OpenCC by scripts/gen-simplified-only.js.
// A name shared by TW and CN (e.g. 原神, 泛舟) has none of them, so it is never mistaken for Simplified.
const SIMPLIFIED_ONLY = new RegExp('[' + require('./simplified-only') + ']', 'u');

// Whether a store name belongs in an edition: Hangul only in ko, kana only in ja, no CJK in en, no Simplified-only characters in zh-tw.
// zh-cn takes any Chinese name: one in Traditional form is shown converted (toSimplified), see rank/stats.js displayName.
const fitsEdition = (name, code) => {
  if (HANGUL.test(name) && code !== 'ko') return false;
  if (KANA.test(name) && code !== 'ja') return false;
  if (code === 'en' && CJK.test(name)) return false;
  return !(code === 'zh-tw' && SIMPLIFIED_ONLY.test(name));
};

// Traditional → Simplified, as OpenCC's t2s does it: at each position the longest phrase of TSPhrases, else the
// character's conversion (data generated by scripts/gen-t2s.js). Phrase level matters for words whose characters all
// exist in Simplified too: 明日之後 → 明日之后, while 皇后 and 乾坤 stay.
const T2S = require('./t2s-data');
const T2S_CHARS = new Map();
{
  const pairs = [...T2S.chars];
  for (let i = 0; i < pairs.length; i += 2) T2S_CHARS.set(pairs[i], pairs[i + 1]);
}
const T2S_MAX_PHRASE = Math.max(...Object.keys(T2S.phrases).map((k) => [...k].length));
const toSimplified = (name) => {
  const chars = [...name];
  let out = '';
  for (let i = 0; i < chars.length;) {
    let length = Math.min(T2S_MAX_PHRASE, chars.length - i);
    let phrase;
    for (; length > 1; length--) {
      phrase = chars.slice(i, i + length).join('');
      if (Object.prototype.hasOwnProperty.call(T2S.phrases, phrase)) break;
    }
    if (length > 1) { out += T2S.phrases[phrase]; i += length; } else { out += T2S_CHARS.get(chars[i]) || chars[i]; i += 1; }
  }
  return out;
};

// Whether a name is written in the edition's own language, as far as its script can show: kana letters (not the
// ・ and ー marks, which Chinese names use too) for ja, Hangul for ko, Han for zh-tw, and for zh-cn Han that the
// Traditional → Simplified conversion leaves unchanged.
const KANA_LETTER = /[\u3041-\u3096\u30A1-\u30FA]/;
const HAN = /[\u3400-\u9FFF]/;
const ownLanguage = (name, code) => {
  if (!fitsEdition(name, code)) return false;
  if (code === 'ja') return KANA_LETTER.test(name);
  if (code === 'ko') return HANGUL.test(name);
  if (code === 'zh-tw') return HAN.test(name);
  return code === 'zh-cn' && HAN.test(name) && toSimplified(name) === name;
};

module.exports = { HANGUL, KANA, CJK, HAN, fitsEdition, ownLanguage, toSimplified };
