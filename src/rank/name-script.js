'use strict';

// Script checks for per-edition game names (rank/stats.js displayName).
const HANGUL = /[\uAC00-\uD7A3]/;
const KANA = /[\u3040-\u30FF]/;
const CJK = /[\u3040-\u30FF\u3400-\u9FFF\uAC00-\uD7A3]/;
// Characters that exist only in Simplified Chinese (never a Traditional form), generated from OpenCC by scripts/gen-simplified-only.js.
// A name shared by TW and CN (e.g. 原神, 泛舟) has none of them, so it is never mistaken for Simplified.
const SIMPLIFIED_ONLY = new RegExp('[' + require('./simplified-only') + ']', 'u');

// Kana letters only: the rest of the kana blocks is punctuation the CJK scripts share (・ in 三國志・戰略版, ー, ゠, ゛),
// which says nothing about a name's language.
const KANA_LETTER = /[\u3041-\u3096\u30A1-\u30FA]/;
const HAN = /[\u3400-\u9FFF]/;

// Whether a store name belongs in an edition: Hangul only in ko, kana only in ja, no CJK in en, no Simplified-only characters in zh-tw.
// zh-cn takes any Chinese name - Japanese text there is what has kana letters - and shows it in Simplified form
// (toSimplified), see rank/stats.js displayName.
const fitsEdition = (name, code) => {
  if (HANGUL.test(name) && code !== 'ko') return false;
  if (code === 'zh-cn' ? KANA_LETTER.test(name) : KANA.test(name) && code !== 'ja') return false;
  if (code === 'en' && CJK.test(name)) return false;
  return !(code === 'zh-tw' && SIMPLIFIED_ONLY.test(name));
};

// One OpenCC conversion step: at each position the longest phrase of the table, else the character's conversion.
const T2S = require('./t2s-data');
const converter = (charPairs, phrases) => {
  const charMap = new Map();
  const pairs = [...charPairs];
  for (let i = 0; i < pairs.length; i += 2) charMap.set(pairs[i], pairs[i + 1]);
  const maxPhrase = Math.max(1, ...Object.keys(phrases).map((k) => [...k].length));
  return (text) => {
    const chars = [...text];
    let out = '';
    for (let i = 0; i < chars.length;) {
      let length = Math.min(maxPhrase, chars.length - i);
      let phrase;
      for (; length > 1; length--) {
        phrase = chars.slice(i, i + length).join('');
        if (Object.prototype.hasOwnProperty.call(phrases, phrase)) break;
      }
      if (length > 1) { out += phrases[phrase]; i += length; } else { out += charMap.get(chars[i]) || chars[i]; i += 1; }
    }
    return out;
  };
};
const shinjitaiToTraditional = converter(T2S.jpChars, T2S.jpPhrases);
const traditionalToSimplified = converter(T2S.chars, T2S.phrases);
// A Chinese name in Simplified form (data generated by scripts/gen-t2s.js): Japanese shinjitai → Traditional (OpenCC
// jp2t), then Traditional → Simplified (OpenCC t2s). 三國志 真戦 → 三国志 真战; the phrase level matters for words whose
// characters all exist in Simplified too (明日之後 → 明日之后, while 皇后 and 乾坤 stay). For names without kana letters only:
// a name with kana is Japanese text and is kept whole.
const toSimplified = (name) => traditionalToSimplified(shinjitaiToTraditional(name));

// Whether a name is written in the edition's own language, as far as its script can show: kana letters for ja,
// Hangul for ko, Han for zh-tw, and for zh-cn Han that toSimplified leaves unchanged (no Traditional or shinjitai form).
const ownLanguage = (name, code) => {
  if (!fitsEdition(name, code)) return false;
  if (code === 'ja') return KANA_LETTER.test(name);
  if (code === 'ko') return HANGUL.test(name);
  if (code === 'zh-tw') return HAN.test(name);
  return code === 'zh-cn' && HAN.test(name) && toSimplified(name) === name;
};

module.exports = { HANGUL, KANA, KANA_LETTER, CJK, HAN, fitsEdition, ownLanguage, toSimplified };
