/**
 * One-shot: generate docs/_redirects for GamerScroll → AIScroll tech migration.
 *
 * Source: data/tech/ai/*.json (site === 'aiscroll' only) + data/tech/vibecoding/*.json
 * Rule: gamerscroll.com/tech/ai/<slug>/  →  aiscroll.io/article/<category>/<slug>/  (301)
 *
 * category for ai dir = JSON.category (openai/google/anthropic/general)
 * category for vibecoding dir = 'vibecoding'
 *
 * Output: docs/_redirects (Cloudflare Pages standard format)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const TECH_AI_DIR = path.join(ROOT, 'data', 'tech', 'ai');
const TECH_VIBE_DIR = path.join(ROOT, 'data', 'tech', 'vibecoding');
const OUTPUT = path.join(ROOT, 'docs', '_redirects');

const lines = [];
lines.push('# GamerScroll → AIScroll redirect map (generated by scripts/gen-gs-redirects.js)');
lines.push('# Stage 3 cleanup: tech/* slugs moved to aiscroll.io with 301.');
lines.push('# Format: <from-path> <to-url> <status>');
lines.push('');

let aiCount = 0;
let vibeCount = 0;
let skipped = 0;

function emit(fromPath, toUrl) {
  lines.push(`${fromPath} ${toUrl} 301`);
}

// tech/ai/<slug> → article/<category>/<slug>
if (fs.existsSync(TECH_AI_DIR)) {
  const files = fs.readdirSync(TECH_AI_DIR).filter(f => f.endsWith('.json'));
  for (const file of files) {
    try {
      const data = JSON.parse(fs.readFileSync(path.join(TECH_AI_DIR, file), 'utf8').replace(/^﻿/, ''));
      if (data.site !== 'aiscroll') { skipped++; continue; }
      const slug = data.slug || file.replace(/\.json$/, '');
      const cat = data.category || 'general';
      emit(`/tech/ai/${slug}/*`, `https://aiscroll.io/article/${cat}/${slug}/:splat`);
      aiCount++;
    } catch (e) {
      skipped++;
    }
  }
}

// tech/vibecoding/<slug> → article/vibecoding/<slug>
if (fs.existsSync(TECH_VIBE_DIR)) {
  const files = fs.readdirSync(TECH_VIBE_DIR).filter(f => f.endsWith('.json'));
  for (const file of files) {
    try {
      const data = JSON.parse(fs.readFileSync(path.join(TECH_VIBE_DIR, file), 'utf8').replace(/^﻿/, ''));
      if (data.site !== 'aiscroll') { skipped++; continue; }
      const slug = data.slug || file.replace(/\.json$/, '');
      emit(`/tech/vibecoding/${slug}/*`, `https://aiscroll.io/article/vibecoding/${slug}/:splat`);
      vibeCount++;
    } catch (e) {
      skipped++;
    }
  }
}

// Hub fallback: any remaining /tech/* lands on aiscroll.io homepage
lines.push('');
lines.push('# Hub fallback for un-migrated tech paths (normal/ + unknown slugs)');
lines.push('/tech/* https://aiscroll.io/ 301');

const content = lines.join('\n') + '\n';

if (!fs.existsSync(path.dirname(OUTPUT))) {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
}
fs.writeFileSync(OUTPUT, content, 'utf8');

console.log(JSON.stringify({
  output: path.relative(ROOT, OUTPUT),
  totalLines: lines.length,
  ai_redirects: aiCount,
  vibecoding_redirects: vibeCount,
  skipped,
  bytes: content.length
}, null, 2));
