'use strict';
// Generates src/rank/traditional-only.js from OpenCC's dictionaries (Apache-2.0, https://github.com/BYVoid/OpenCC,
// data/dictionary/STCharacters.txt and TSCharacters.txt), the mirror of scripts/gen-simplified-only.js:
//   node scripts/gen-traditional-only.js <dir with STCharacters.txt and TSCharacters.txt>
// A character is Traditional-only when it is converted by TSCharacters (never maps to itself) and is never itself a
// Simplified form (not a key of STCharacters) and is not in GB 2312, the mainland standard charset - OpenCC also lists
// pairs whose Traditional side is valid Simplified (乾/干 as in 乾坤, 著/着 as in 著名), and GB 2312 keeps those out.
// Single-character keys only.
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/)
  .filter((l) => l && !l.startsWith('#')).map((l) => { const [k, v] = l.split('\t'); return [k, v.split(' ')]; });

// GB 2312 hanzi rows (0xB0-0xF7); the gbk decoder covers them at the same code points.
const gb2312 = new Set();
const decoder = new TextDecoder('gbk');
for (let hi = 0xB0; hi <= 0xF7; hi++) {
  for (let lo = 0xA1; lo <= 0xFE; lo++) {
    const ch = decoder.decode(Uint8Array.of(hi, lo));
    if ([...ch].length === 1 && ch !== '\uFFFD') gb2312.add(ch);
  }
}

const simplifiedForms = new Set(read('STCharacters.txt').map(([k]) => k));
const chars = read('TSCharacters.txt')
  .filter(([k, v]) => [...k].length === 1 && !v.includes(k) && !simplifiedForms.has(k) && !gb2312.has(k))
  .map(([k]) => k).sort();

fs.writeFileSync(path.join(__dirname, '../src/rank/traditional-only.js'),
  `'use strict';
// Generated by scripts/gen-traditional-only.js from OpenCC STCharacters/TSCharacters (Apache-2.0). Do not edit.
module.exports = ${JSON.stringify(chars.join(''))};
`);
console.log(chars.length, 'characters');
