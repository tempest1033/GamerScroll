'use strict';
// Generates src/rank/simplified-only.js from OpenCC's dictionaries (Apache-2.0, https://github.com/BYVoid/OpenCC,
// data/dictionary/STCharacters.txt and TSCharacters.txt):
//   node scripts/gen-simplified-only.js <dir with STCharacters.txt and TSCharacters.txt>
// A character is Simplified-only when it is converted by STCharacters (never maps to itself) and is never itself a
// Traditional form (not a key of TSCharacters) and is not in Big5, the Taiwan standard charset - OpenCC also lists variant pairs
// (峰/峯, 群/羣, 秘/祕) that are valid Traditional in Taiwan, and Big5 keeps those out. Single-character keys only.
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/)
  .filter((l) => l && !l.startsWith('#')).map((l) => { const [k, v] = l.split('\t'); return [k, v.split(' ')]; });

const big5 = new Set();
const decoder = new TextDecoder('big5');
for (let hi = 0xA1; hi <= 0xF9; hi++) {
  for (let lo = 0x40; lo <= 0xFE; lo++) {
    if (lo > 0x7E && lo < 0xA1) continue;
    const ch = decoder.decode(Uint8Array.of(hi, lo));
    if ([...ch].length === 1 && ch !== '\uFFFD') big5.add(ch);
  }
}

const traditionalForms = new Set(read('TSCharacters.txt').map(([k]) => k));
const chars = read('STCharacters.txt')
  .filter(([k, v]) => [...k].length === 1 && !v.includes(k) && !traditionalForms.has(k) && !big5.has(k))
  .map(([k]) => k).sort();

fs.writeFileSync(path.join(__dirname, '../src/rank/simplified-only.js'),
  `'use strict';
// Generated by scripts/gen-simplified-only.js from OpenCC STCharacters/TSCharacters (Apache-2.0). Do not edit.
module.exports = ${JSON.stringify(chars.join(''))};
`);
console.log(chars.length, 'characters');
