'use strict';
// Generates src/rank/t2s-data.js from OpenCC's dictionaries (Apache-2.0, https://github.com/BYVoid/OpenCC,
// data/dictionary/TSPhrases.txt and TSCharacters.txt), the two dictionaries of OpenCC's t2s conversion
// (data/config/t2s.json; its TSCharactersExt and compatibility-ideograph normalization are left out),
// and from JPShinjitaiCharacters.txt and JPShinjitaiPhrases.txt, the two dictionaries of its jp2t conversion (data/config/jp2t.json):
//   node scripts/gen-t2s.js <dir with those four files>
// t2s: each entry keeps OpenCC's first (preferred) conversion. Phrases that convert to themselves stay in the table: they
// keep a word such as 乾坤 from being converted character by character. Characters that convert to themselves are dropped.
// jp2t is narrowed to forms that are Japanese only, because it runs on Chinese names too and must leave them alone:
//   - a character is taken only when it is neither in GB 2312 (the mainland standard charset: 研, 欠, 郎, 芸 are valid
//     Simplified, and jp2t would turn them into 硏, 缺, 郞, 藝) nor a Traditional character t2s converts itself (並);
//   - its target is the first form other than itself (OpenCC lists 産 → 産 產; left as 産 it would stay shinjitai),
//     preferring one t2s takes on to a GB 2312 character (闘 → 鬥 → 斗, not 鬭, which t2s does not know);
//   - a phrase is taken only when it contains such a character (暴露 → 曝露 and 先端 → 尖端 would rewrite Chinese words).
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
const byKey = ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0);
const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/)
  .filter((l) => l && !l.startsWith('#')).map((l) => { const [k, v] = l.split('\t'); return [k, v.split(' ')]; });

const tsCharacters = read('TSCharacters.txt');
const phrases = Object.fromEntries(read('TSPhrases.txt').map(([k, v]) => [k, v[0]]).sort(byKey));
const chars = tsCharacters.map(([k, v]) => [k, v[0]]).filter(([k, v]) => k !== v).sort(byKey);

// GB 2312 hanzi rows (0xB0-0xF7); the gbk decoder covers them at the same code points.
const gb2312 = new Set();
const decoder = new TextDecoder('gbk');
for (let hi = 0xB0; hi <= 0xF7; hi++) {
  for (let lo = 0xA1; lo <= 0xFE; lo++) {
    const ch = decoder.decode(Uint8Array.of(hi, lo));
    if ([...ch].length === 1 && ch !== '\uFFFD') gb2312.add(ch);
  }
}
const traditional = new Set(tsCharacters.map(([k]) => k));
const simplifiedOf = new Map(tsCharacters.map(([k, v]) => [k, v[0]]));
const reachesSimplified = (x) => gb2312.has(simplifiedOf.get(x) || x);
const jpChars = read('JPShinjitaiCharacters.txt')
  .filter(([k]) => !gb2312.has(k) && !traditional.has(k))
  .map(([k, v]) => { const forms = v.filter((x) => x !== k); return [k, forms.find(reachesSimplified) || forms[0]]; })
  .filter(([, v]) => v).sort(byKey);
const japaneseOnly = new Set(jpChars.map(([k]) => k));
const jpPhrases = Object.fromEntries(read('JPShinjitaiPhrases.txt')
  .filter(([k]) => [...k].some((c) => japaneseOnly.has(c)))
  .map(([k, v]) => [k, v.find((x) => x !== k)]).filter(([, v]) => v).sort(byKey));

fs.writeFileSync(path.join(__dirname, '../src/rank/t2s-data.js'),
  `'use strict';
// Generated by scripts/gen-t2s.js from OpenCC TSPhrases/TSCharacters and JPShinjitaiPhrases/JPShinjitaiCharacters (Apache-2.0). Do not edit.
// chars: Traditional character followed by its Simplified form, pair after pair. phrases: Traditional phrase → Simplified.
// jpChars, jpPhrases: the same for Japanese shinjitai → Traditional.
module.exports = {
  chars: ${JSON.stringify(chars.map(([k, v]) => k + v).join(''))},
  phrases: ${JSON.stringify(phrases)},
  jpChars: ${JSON.stringify(jpChars.map(([k, v]) => k + v).join(''))},
  jpPhrases: ${JSON.stringify(jpPhrases)},
};
`);
console.log(chars.length, 'characters,', Object.keys(phrases).length, 'phrases; shinjitai:', jpChars.length, 'characters,', Object.keys(jpPhrases).length, 'phrases');
