'use strict';
// Generates src/rank/t2s-data.js from OpenCC's dictionaries (Apache-2.0, https://github.com/BYVoid/OpenCC,
// data/dictionary/TSPhrases.txt and TSCharacters.txt), the two dictionaries of OpenCC's t2s conversion
// (data/config/t2s.json; its TSCharactersExt and compatibility-ideograph normalization are left out):
//   node scripts/gen-t2s.js <dir with TSPhrases.txt and TSCharacters.txt>
// Each entry keeps OpenCC's first (preferred) conversion. Phrases that convert to themselves stay in the table: they
// keep a word such as 乾坤 from being converted character by character. Characters that convert to themselves are dropped.
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/)
  .filter((l) => l && !l.startsWith('#')).map((l) => { const [k, v] = l.split('\t'); return [k, v.split(' ')[0]]; });

const phrases = Object.fromEntries(read('TSPhrases.txt').sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const chars = read('TSCharacters.txt').filter(([k, v]) => k !== v).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

fs.writeFileSync(path.join(__dirname, '../src/rank/t2s-data.js'),
  `'use strict';
// Generated by scripts/gen-t2s.js from OpenCC TSPhrases/TSCharacters (Apache-2.0). Do not edit.
// chars: Traditional character followed by its Simplified form, pair after pair. phrases: Traditional phrase → Simplified.
module.exports = {
  chars: ${JSON.stringify(chars.map(([k, v]) => k + v).join(''))},
  phrases: ${JSON.stringify(phrases)},
};
`);
console.log(chars.length, 'characters,', Object.keys(phrases).length, 'phrases');
