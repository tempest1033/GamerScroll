const assert = require('node:assert/strict');
const cheerio = require('cheerio');
const { loadRankStats, COUNTRIES, STORES } = require('../src/rank/stats');
const { renderMonthly, renderGlobal } = require('../src/templates/pages/rank-hub');
const S = loadRankStats();
const rows = Object.fromEntries(Object.keys(COUNTRIES).map(c => [c, Object.fromEntries(Object.keys(STORES).map(s => [s, []]))]));
rows.kr.ios = Array.from({ length: 201 }, (_, i) => ({ appId: `test-rank-${i}`, title: `Test ${i}` }));
rows.cn.android = [{ appId: 'excluded-cn-android', title: 'Excluded' }];
const list = S.aggregateGlobal({ rows }).list;
assert.equal(list.length, 200);
assert.equal(list[0].pts, 200);
assert.equal(list.at(-1).pts, 1);
assert(!list.some(row => row.row.appId === 'excluded-cn-android'));
rows.jp.ios = [rows.kr.ios[0]];
assert.equal(S.aggregateGlobal({ rows }).list[0].pts, 400, '국가별 기여 합산');
rows.kr.ios = [rows.kr.ios[0], rows.kr.ios[0]];
assert.equal(S.aggregateGlobal({ rows }).list[0].pts, 400, '같은 차트의 동일 게임 중복 합산 금지');
console.log('PASS chart-index endpoints, scope, aggregation, duplicate handling');

const $ = cheerio.load(renderMonthly('2026-08'));
assert.equal($('.rk-month-summary > .rk-month-publishers').length, 1);
assert.equal($('.rk-month-summary > .rk-month-brief').length, 1);
assert.equal($('.rk-month-brief h2').text().includes('8월 순위 요약'), true);
assert.equal($('.rk-month-summary').text().includes('서브컬처'), false);
assert.equal($('.rk-month-publishers .rk-publisher-cell').length, 10);
assert.equal($('.rk-month-publishers img').length, 10);
assert.equal($('.rk-month-brief dl > div').length, 4);
const previous = cheerio.load(renderMonthly('2026-07'));
assert.equal(previous('.rk-month-brief h2').text().includes('7월 순위 요약'), true);
const global = cheerio.load(renderGlobal());
assert.equal(global('.rk-global-country,.rk-global-store').length, 0);
assert.equal(global('.rk-global-index').is('details'), false);
assert.equal(global('.rk-global-index tbody tr').length, 100);
assert.equal(global('h1').text(), '글로벌 차트 지수');
console.log('PASS monthly layout, marks, month selection, always-visible global index');
